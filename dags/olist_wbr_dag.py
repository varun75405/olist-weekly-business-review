"""
dags/olist_wbr_dag.py
Apache Airflow DAG definition for the Olist Weekly Business Review ELT Pipeline.
Orchestrates atomic ingestion, raw DQ validation, staging/mart transforms,
analytical query execution, chart generation, and PDF report compilation.
"""
from datetime import datetime, timedelta

try:
    from airflow import DAG
    from airflow.operators.python import PythonOperator
    from airflow.operators.empty import EmptyOperator
    AIRFLOW_AVAILABLE = True
except ImportError:
    AIRFLOW_AVAILABLE = False


def task_validate_and_ingest():
    from src.ingest import run_ingestion
    return run_ingestion()


def task_quality_checks():
    from src.quality_checks import run_quality_checks
    return run_quality_checks()


def task_transform():
    from src.transform import run_transform
    return run_transform()


def task_run_queries():
    from src.run_queries import run_all_queries
    from src.db import get_engine
    results = run_all_queries()
    engine = get_engine()
    with engine.begin() as conn:
        for qname, df in results.items():
            df.to_sql(qname, conn, schema="analytics", if_exists="replace", index=False)
    return {k: len(v) for k, v in results.items()}


def task_generate_charts():
    from src.generate_charts import generate_all_charts
    from src.db import get_engine
    from src.run_queries import QUERIES
    import pandas as pd

    engine = get_engine()
    qr = {}
    with engine.connect() as conn:
        for qname, _ in QUERIES:
            qr[qname] = pd.read_sql(f"SELECT * FROM analytics.{qname}", conn)

    return generate_all_charts(qr)


def task_build_report():
    from src.build_report import build_pdf
    from src.config import CHARTS_DIR
    from src.db import get_engine
    from src.run_queries import QUERIES
    from sqlalchemy import text
    import pandas as pd

    engine = get_engine()

    # 1. Load query results from database tables populated by task_run_queries
    query_results = {}
    with engine.connect() as conn:
        for qname, _ in QUERIES:
            query_results[qname] = pd.read_sql(f"SELECT * FROM analytics.{qname}", conn)

    # 2. Load latest data quality audit results populated by task_quality_checks
    with engine.connect() as conn:
        rows = conn.execute(text("""
            SELECT check_name, description, is_hard_fail, failing_rows, sample_ids, status
            FROM (
                SELECT DISTINCT ON (check_name)
                    id, check_name, description, is_hard_fail, failing_rows, sample_ids, status
                FROM analytics.dq_audit
                ORDER BY check_name, id DESC
            ) sub
            ORDER BY id ASC;
        """)).fetchall()
        dq_results = [dict(r._mapping) for r in rows]

    # 3. Reference visualization artifacts generated by task_generate_charts
    chart_paths = {
        "chart1": CHARTS_DIR / "chart1_monthly_revenue.png",
        "chart2": CHARTS_DIR / "chart2_top_categories.png",
        "chart3": CHARTS_DIR / "chart3_delivery_vs_review.png",
        "chart4": CHARTS_DIR / "chart4_rolling_orders.png",
    }

    # 4. Compile executive PDF report using outputs from upstream tasks
    return build_pdf(query_results, dq_results, chart_paths)


default_args = {
    "owner": "analytics_team",
    "depends_on_past": False,
    "start_date": datetime(2026, 1, 1),
    "email_on_failure": False,
    "email_on_retry": False,
    "retries": 1,
    "retry_delay": timedelta(minutes=5),
}

if AIRFLOW_AVAILABLE:
    dag = DAG(
        "olist_weekly_business_review",
        default_args=default_args,
        description="Weekly Business Review ELT Pipeline for Olist Marketplace",
        schedule_interval="0 6 * * *",  # Daily at 06:00 UTC
        catchup=False,
        tags=["olist", "wbr", "analytics", "elt"],
    )

    start = EmptyOperator(task_id="start", dag=dag)

    ingest = PythonOperator(
        task_id="validate_and_ingest_raw",
        python_callable=task_validate_and_ingest,
        dag=dag,
    )

    raw_dq = PythonOperator(
        task_id="run_raw_data_quality_checks",
        python_callable=task_quality_checks,
        dag=dag,
    )

    transform = PythonOperator(
        task_id="staging_and_mart_transform",
        python_callable=task_transform,
        dag=dag,
    )

    analytics = PythonOperator(
        task_id="execute_analytical_queries",
        python_callable=task_run_queries,
        dag=dag,
    )

    charts = PythonOperator(
        task_id="generate_visualizations",
        python_callable=task_generate_charts,
        dag=dag,
    )

    report = PythonOperator(
        task_id="compile_pdf_report",
        python_callable=task_build_report,
        dag=dag,
    )

    end = EmptyOperator(task_id="end", dag=dag)

    # Dependency sequence: Raw Ingest -> Raw DQ -> Staging/Mart -> Analytics -> Charts -> Report -> End
    start >> ingest >> raw_dq >> transform >> analytics >> charts >> report >> end
